export function editorText(
  locale: EditorLocale, message: string, values: Readonly<Record<string, string | number>> = {},
): string {
  const template = locale === 'zh' && Object.hasOwn(chinese, message) ? chinese[message]! : message;
  return template.replace(/\{([A-Za-z]+)\}/g, (placeholder, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder);
}

