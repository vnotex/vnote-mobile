// Reconfigure this extension in its own compartment. Never create an EditorState
// for a preference change: document, directed selection and history stay owned
// by the existing state and the protocol's composition barrier.
export function editorPresentation(locale: EditorLocale, language: 'markdown' | 'text'): Extension {
  return [
    EditorState.phrases.of(locale === 'zh' ? chinesePhrases : {}),
    EditorView.contentAttributes.of({
      'aria-label': editorText(locale, language === 'markdown' ? 'Markdown source editor' : 'Plain text source editor'),
      'aria-describedby': 'status',
      'lang': locale === 'zh' ? 'zh-CN' : 'en',
      spellcheck: 'false', autocapitalize: 'off', autocorrect: 'off',
    }),
  ];
}
